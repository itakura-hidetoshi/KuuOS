"""v0.34: original file-backed ActStore genesis and committed history.

The fixture uses original Plan/Act/WORLD OS constructors and store files.
The Plan activation receipt is regenerated by the SAME original
constructor and original v1.3 fixture parameters (not an external receipt).
No original proof-objects or numeric ActOS job-count witnesses are claimed.
Copyright Hidetoshi Itakura / 板倉英俊. Apache-2.0.
"""
from __future__ import annotations

from copy import deepcopy
import json
from pathlib import Path
import shutil
from tempfile import TemporaryDirectory
import unittest

from runtime.kuuos_belief_os_types_v0_1 import sha
from runtime.kuuos_plan_os_kernel_v0_1 import build_plan_phase_activation_receipt
from runtime.kuuos_qi_world_native_full_cycle_v1_3 import (
    build_native_full_cycle_receipt, validate_native_full_cycle_receipt,
)
from runtime.kuuos_act_os_store_v0_1 import ActStore
from runtime.kuuos_lean_python_plan_act_store_provenance_v0_34 import (
    audit_native_plan_act_store_compatibility,
    SCOPED_COMPATIBLE, NO_DATA, BLOCKED, NUMERIC_AND_ISSUER_OBSTRUCTIONS,
)


class NativePlanActStoreProvenanceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = TemporaryDirectory(prefix="kuuos-v034-plan-act-")
        cls.addClassCleanup(cls.tmp.cleanup)
        cls.root = Path(cls.tmp.name)
        cls.native = build_native_full_cycle_receipt(cls.root)
        assert validate_native_full_cycle_receipt(cls.native) == []
        cls.plan = cls.native["native_artifacts"]["PlanOS"]
        cls.final = cls.native["native_artifacts"]["ActOS"]
        cls.activation = build_plan_phase_activation_receipt(
            state=cls.plan,
            mission_cycle_phase="plan",
            mission_cycle_state_digest=sha("native-full-cycle-plan-phase-state"),
            plan_phase_receipt_digest=sha("native-full-cycle-plan-phase-receipt"),
            now_ms=80_000,
        )
        cls.act_root = cls.root / "act"

    def audit(self, *, plan=None, receipt=None, final=None, root=None):
        return audit_native_plan_act_store_compatibility(
            self.plan if plan is None else plan,
            self.activation if receipt is None else receipt,
            self.final if final is None else final,
            self.act_root if root is None else root,
        )

    def test_full_original_act_store_replays_to_exact_committed_state(self):
        self.assertEqual(ActStore(self.act_root).recover(), self.final)
        self.assertEqual(validate_native_full_cycle_receipt(self.native), [])
        self.assertEqual(self.final["current_phase"], "commit")

    def test_original_plan_act_local_store_relationship(self):
        a = self.audit()
        self.assertEqual(a.status, SCOPED_COMPATIBLE, a.issues)
        self.assertTrue(a.original_plan_guard_checked)
        self.assertTrue(a.original_initial_admission_checked)
        self.assertTrue(a.original_act_ledger_replayed)
        self.assertTrue(a.original_final_act_local_conditions_checked)
        self.assertGreater(a.ledger_commit_count, 0)
        self.assertEqual(a.missing_lean_witnesses, NUMERIC_AND_ISSUER_OBSTRUCTIONS)

    def test_missing_activation_receipt_is_no_data(self):
        self.assertEqual(audit_native_plan_act_store_compatibility(
            self.plan, None, self.final, self.act_root).status, NO_DATA)

    def test_missing_final_state_is_no_data(self):
        self.assertEqual(audit_native_plan_act_store_compatibility(
            self.plan, self.activation, None, self.act_root).status, NO_DATA)

    def test_missing_store_root_is_no_data(self):
        self.assertEqual(self.audit(root=self.root / "missing-act-store").status, NO_DATA)

    def test_wrong_path_object_is_blocked(self):
        self.assertEqual(self.audit(root=[]).status, BLOCKED)

    def test_forged_activation_digest_is_blocked(self):
        r = deepcopy(self.activation)
        r["plan_activation_receipt_digest"] = "forged"
        self.assertEqual(self.audit(receipt=r).status, BLOCKED)

    def test_forged_activation_host_permission_is_blocked(self):
        r = deepcopy(self.activation)
        r["host_license_granted"] = True
        self.assertEqual(self.audit(receipt=r).status, BLOCKED)

    def test_forged_plan_step_guard_is_blocked(self):
        p = deepcopy(self.plan)
        p["guard_summary"]["all_effects_guarded"] = False
        self.assertEqual(self.audit(plan=p).status, BLOCKED)

    def test_forged_final_act_source_link_is_blocked(self):
        a = deepcopy(self.final)
        a["source_plan_state_digest"] = "forged"
        self.assertEqual(self.audit(final=a).status, BLOCKED)

    def test_store_snapshot_corruption_blocks(self):
        with TemporaryDirectory(prefix="kuuos-v034-corrupt-") as tmp:
            copied = Path(tmp) / "act"
            shutil.copytree(self.act_root, copied)
            path = copied / "act-snapshot.json"
            record = json.loads(path.read_text(encoding="utf-8"))
            record["act_state_digest"] = "forged"
            path.write_text(json.dumps(record), encoding="utf-8")
            self.assertEqual(self.audit(root=copied).status, BLOCKED)

    def test_store_ledger_corruption_blocks(self):
        with TemporaryDirectory(prefix="kuuos-v034-corrupt-") as tmp:
            copied = Path(tmp) / "act"
            shutil.copytree(self.act_root, copied)
            with (copied / "act-ledger.jsonl").open("a", encoding="utf-8") as f:
                f.write("{}\n")
            self.assertEqual(self.audit(root=copied).status, BLOCKED)

    def test_missing_store_ledger_is_no_data(self):
        with TemporaryDirectory(prefix="kuuos-v034-missing-") as tmp:
            copied = Path(tmp) / "act"
            shutil.copytree(self.act_root, copied)
            (copied / "act-ledger.jsonl").unlink()
            self.assertEqual(self.audit(root=copied).status, NO_DATA)

    def test_symlink_store_root_is_rejected(self):
        with TemporaryDirectory(prefix="kuuos-v034-link-") as tmp:
            link = Path(tmp) / "act-link"
            link.symlink_to(self.act_root, target_is_directory=True)
            self.assertEqual(self.audit(root=link).status, BLOCKED)

    def test_original_state_and_store_bytes_unchanged_by_audit(self):
        old = {
            str(p.relative_to(self.root)): p.read_bytes()
            for p in self.root.rglob("*") if p.is_file()
        }
        self.assertEqual(self.audit().status, SCOPED_COMPATIBLE)
        new = {
            str(p.relative_to(self.root)): p.read_bytes()
            for p in self.root.rglob("*") if p.is_file()
        }
        self.assertEqual(old, new)

    def test_all_external_and_formal_boundaries_remain_false(self):
        result = self.audit()
        self.assertEqual(result.status, SCOPED_COMPATIBLE)
        for field in (
            "whole_act_lean_conditions_certified", "formal_descent_certified",
            "global_gluing_proved", "complete_lean_python_refinement_proved",
            "external_activation_issuer_authenticated",
            "actual_numeric_job_and_slice_counts_proved",
            "execution_authority_granted", "host_license_granted",
            "truth_authority_granted", "git_authority_granted",
            "original_store_mutated",
        ):
            self.assertIs(getattr(result, field), False, field)


if __name__ == "__main__":
    unittest.main()
