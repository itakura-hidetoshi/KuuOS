from runtime import kuuos_codeai_intent_repository_observation_envelope_v0_1 as observation
from runtime import kuuos_codeai_autonomous_structured_edit_synthesis_v0_1 as synth
from runtime.kuuos_codeai_candidate_patch_envelope_v0_1 import (
    SOURCE_RECEIPT_DIGEST_FIELD, seal, canonical_digest,
)
from scripts.ci_kuuos_v176_exact_source_audit_v1 import verify_inputs, blob

ROOT = Path(__file__).resolve().parents[1]
REPO = "itakura-hidetoshi/KuuOS"
BASELINE_HEAD = "14bfe7522997b6ca0b2f33390f5de6ae23c9bcf4"
BASELINE_TREE = "1ed4b80bb823424a8660a7f0484dd8adf88c42b7"
BASELINE_BRANCH = "validation/kuuos-v189-codeai-r2-20261122"
PARENT_SOURCE = "formal/KUOS/DependentOriginationCanonicalAttachmentScalingObstructionRetractV1_88.lean"
R1_PATH = "formal/KUOS/DependentOriginationStandardArbitraryScalingWaypointCodeAICandidateR2V1_89.lean"
R2_PATH = "formal/KUOS/DependentOriginationStandardArbitraryScalingWaypointCodeAICandidateR3V1_89.lean"
PINNED_BLOBS = {
 PARENT_SOURCE:"60283850a5de58e88705735379f208dd31d797df",
 R1_PATH:"556208d79118b5b8f332e7fc49ba3657c15b4c20",
}
R2_BLOB = os.environ.get("KUUOS_R3_SOURCE_BLOB","")
OUT = ROOT / "artifacts/codeai-v189-r3-live-mcp-native-governance"

def baseline_files():
    verify_inputs()
    source={}
    for path,sha in PINNED_BLOBS.items():
        data=(ROOT/path).read_bytes()
        if blob(data)!=sha: raise AssertionError("CODEAI_SOURCE_BLOB_DRIFT:"+path)
        source[path]=data.decode("utf8")
    if blob((ROOT/R2_PATH).read_bytes())!=R2_BLOB:
        raise AssertionError("CODEAI_R2_CANDIDATE_DRIFT")
    return source

