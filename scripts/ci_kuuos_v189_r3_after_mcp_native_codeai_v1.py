#!/usr/bin/env python3
"""Run genuine KuuOS CodeAI after real Lean MCP generated R3 proof-only candidate.

R3 is generated by deterministic diagnostic-guided provider only after real
Lean MCP observations, not supplied by an LLM. KuuOS-native CodeAI runs its
actual source-bound synthesis and CANDIDATE / false-authority REJECT checks.
No independent proof, verified-useful Memory, or Git authority is asserted.
"""
