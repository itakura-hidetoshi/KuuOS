#!/usr/bin/env python3
"""KuuOS native CodeAI: three model-supplied v0.61 Lean proof candidates.

This runs the ACTUAL repository CodeAI observation/synthesis/provider-boundary/
Candidate-Patch/diff-ranking kernels with separate, full-text proof alternatives.
Sources were prepared by the assistant and committed as proposal-only examples,
NOT generated by a live CodeAI provider inference call. One synthetic provider
asserts authority and is rejected. No Git effects, theorem authority or merge.
Only exact original canonical main blobs are admitted to the read-only prompt.

All three candidates must be tested with pinned Lean separately. CodeAI ranking
is advisory and does not select a theorem or authorize adoption.
"""
from __future__ import annotations
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import time

from runtime import kuuos_codeai_autonomous_structured_edit_synthesis_v0_1 as synth
from runtime.kuuos_codeai_candidate_patch_envelope_v0_1 import (
    SOURCE_RECEIPT_DIGEST_FIELD, seal
)
from scripts import codeai_v061_two_stage_proof_proposal as base

ROOT = base.ROOT
INPUTS = (
    ("model-a", base.PROPOSAL_SOURCE),
    ("model-b", "examples/codeai_v061_two_stage_private_append_variant_b.lean.txt"),
    ("model-c", "examples/codeai_v061_two_stage_private_append_variant_c.lean.txt"),
)
OUTPUT = ROOT / "artifacts" / "codeai-v061-three-candidates"


def run_portfolio() -> dict:
    repo = base._read_pinned_snapshot()
    epoch = int(time.time())
    observation_receipt = base._fresh_observation(repo, epoch)
    fixture = json.loads((ROOT /
        "examples/codeai_autonomous_structured_edit_synthesis_v0_1.json"
        ).read_text(encoding="utf-8"))
    example_policy = json.loads((ROOT /
        "examples/codeai_candidate_patch_envelope_v0_1.json"
        ).read_text(encoding="utf-8"))
    request = deepcopy(fixture["synthesis_request"])
    request.update(
        request_id="codeai-v061-three-proof-candidate-portfolio",
        request_revision="r1",
        intent_text="Compare three bounded proof alternatives for exact two-stage tagged-private append, without weakening v0.60 semantics or PlanOS authority.",
        candidate_count=4,
        request_created_epoch=epoch,
        requirement_trace_ids=["research:v061:two-stage-composition"],
        test_plan_ids=["pinned-Lean-direct","real-lean-mcp","independent-axioms"],
        risk_labels=["formal"],
        unresolved_candidate_questions=[],
        prior_candidate_digests=[],
        prior_producer_session_ids=[],
    )
    request=seal(request, synth.REQUEST_DIGEST_FIELD)
    policy=deepcopy(fixture["synthesis_policy"])
    policy.update(
        allowed_provider_ids=["gpt","local_model"],
        maximum_provider_calls=4,
        maximum_proposals=4,
        maximum_raw_output_bytes=60000,
        maximum_repository_snapshot_bytes=300000,
        allowed_repository_path_prefixes=["formal/KUOS/Architecture","formal/KUOS/PlanOS"],
        forbidden_repository_path_prefixes=["formal/KUOS/Architecture/private"],
        evaluation_epoch=epoch,
    )
    policy=seal(policy, synth.POLICY_DIGEST_FIELD)
    candpol=deepcopy(example_policy["candidate_policy"])
    candpol.update(
        expected_source_observation_receipt_digest=
            observation_receipt[SOURCE_RECEIPT_DIGEST_FIELD],
        expected_source_commit_sha=base.MAIN_HEAD,
        expected_repository_full_name="itakura-hidetoshi/KuuOS",
        allowed_path_prefixes=["formal/KUOS/Architecture"],
        forbidden_path_prefixes=["formal/KUOS/Architecture/private"],
        maximum_patch_bytes=200000,
        known_risk_labels=["formal","documentation","release","security"],
        handover_risk_labels=["release","security"],
        evaluation_epoch=epoch,
        maximum_candidate_age=3600,
    )
    candpol=seal(candpol,"codeai_candidate_patch_policy_digest")
    adapters=[]
    hashes={}
    for label,name in INPUTS:
        source=(ROOT/name).read_text(encoding="utf-8")
        assert source.startswith("import Mathlib\n") and source.endswith("\n")
        assert source.count("#print axioms ")==len(base.AXIOM_NAMES)
        hashes[label]=hashlib.sha256(source.encode("utf-8")).hexdigest()
        raw={"proposal_id":"codeai-v061-"+label,
             "candidate_revision":"r1",
             "edits":[{"path":base.CANDIDATE_PATH,
                       "operation":"add","new_content":source}],
             "risk_labels":["formal"],
             "unresolved_candidate_questions":[]}
        response={
            "provider_response_id":"v061-model-supplied-"+label,
            "producer_session_id":"v061-model-supplied-"+label,
            "response_created_epoch":epoch,
            "raw_output":json.dumps(raw,ensure_ascii=False,sort_keys=True,
                                    separators=(",",":")),
            "claims_authority":False,
            "hides_uncertainty":False,
            "bypasses_governance":False,
            "evidence_missing":False,
        }
        adapters.append(synth.ProviderAdapter(
            label,"gpt","assistant-model-supplied-"+label,
            lambda _prompt,response=response:response))
    rejected=dict(response)
    rejected.update(
        provider_response_id="v061-synthetic-rejected",
        producer_session_id="v061-synthetic-rejected",
        claims_authority=True,
    )
    adapters.append(synth.ProviderAdapter(
        "z-synthetic-rejected","local_model",
        "synthetic-untrusted-actor-claims-authority",
        lambda _prompt: rejected))
    result=synth.build_codeai_autonomous_structured_edit_synthesis(
        source_observation_receipt=observation_receipt,
        repository_files=repo,
        synthesis_request=request,
        provider_adapters=adapters,
        synthesis_policy=policy,
        candidate_policy=candpol,
    )
    if result.status!=synth.STATUS_READY or len(result.candidates)!=3:
        raise AssertionError(("CodeAI_proposal_failure",
                              result.status,result.issues,
                              [x.boundary_status for x in result.attempts]))
    accepted=[a.boundary_status for a in result.attempts]
    assert accepted==[synth.BOUNDARY_CANDIDATE]*3+[synth.BOUNDARY_REJECT], accepted
    assert result.receipt is not None
    assert not result.receipt["candidate_selected"]
    assert not result.receipt["repository_mutation_performed"]
    assert not result.receipt["verification_authority_granted"]
    assert not result.receipt["merge_authority_granted"]
    assert result.receipt["generated_candidate_count"]==3
    assert result.receipt["provider_call_count"]==4

    OUTPUT.mkdir(parents=True,exist_ok=True)
    observed=[]
    for c in result.candidates:
        patch=c.patch_candidate
        assert patch["source_commit_sha"]==base.MAIN_HEAD
        assert patch["changed_paths"]==[base.CANDIDATE_PATH]
        assert patch["added_paths"]==[base.CANDIDATE_PATH]
        observed.append({
            "rank":c.rank,
            "proposal_id":c.proposal_id,
            "candidate_digest":patch["codeai_candidate_patch_digest"],
            "source_head":patch["source_commit_sha"],
            "patch_sha256":hashlib.sha256(c.patch_artifact.encode()).hexdigest(),
        })
        (OUTPUT/(c.proposal_id+".diff")).write_text(
            c.patch_artifact,encoding="utf-8")
    assert {x["proposal_id"] for x in observed} == {
        "codeai-v061-"+label for label,_ in INPUTS
    }
    summary={
        "source_main_head":base.MAIN_HEAD,
        "source_main_tree":base.MAIN_TREE,
        "model_material_origin":"three_model_supplied_examples_not_live_codeai_inference",
        "candidate_hashes":hashes,
        "codeai_source_receipt_digest":
            observation_receipt[SOURCE_RECEIPT_DIGEST_FIELD],
        "codeai_synthesis_receipt_digest":
            result.receipt[synth.RECEIPT_DIGEST_FIELD],
        "attempts":accepted,
        "candidate_count":len(observed),
        "ranked_codeai_candidates":observed,
        "selected":False,
        "all_direct_lean_certified":False,
        "real_lean_mcp_certified":False,
        "independent_ci_certified":False,
        "git_mutation_by_codeai":False,
        "execution_or_merge_authority":False,
    }
    (OUTPUT/"receipt.json").write_text(
        json.dumps(summary,ensure_ascii=False,sort_keys=True,indent=2)+"\n",
        encoding="utf-8")
    print("KUUOS_CODEAI_V061_THREE_CANDIDATES:",json.dumps(
        summary,ensure_ascii=False,sort_keys=True))
    return summary


if __name__=="__main__":
    run_portfolio()
